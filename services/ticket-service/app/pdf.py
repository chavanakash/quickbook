from datetime import datetime
from io import BytesIO

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

BRAND = colors.HexColor("#1d4ed8")


def _fmt(iso_value: str) -> str:
    return datetime.fromisoformat(iso_value).strftime("%d %b %Y, %H:%M")


def _table(rows, col_widths, header=True):
    table = Table(rows, colWidths=col_widths, hAlign="LEFT")
    style = [
        ("FONTSIZE", (0, 0), (-1, -1), 10),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]
    if header:
        style += [
            ("BACKGROUND", (0, 0), (-1, 0), BRAND),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ]
    table.setStyle(TableStyle(style))
    return table


def build_ticket_pdf(booking: dict) -> bytes:
    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        title=f"Ticket {booking['pnr']}",
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
    )
    styles = getSampleStyleSheet()
    mode = "Flight" if booking["mode"] == "flight" else "Train"

    # User-supplied values go into Table cells (plain text), never into Paragraph markup.
    elements = [
        Paragraph(f'<font color="#1d4ed8">QuickBook</font> {mode} E-Ticket', styles["Title"]),
        _table(
            [["PNR", booking["pnr"], "Status", booking["status"]]],
            [30 * mm, 50 * mm, 30 * mm, 64 * mm],
            header=False,
        ),
        Spacer(1, 8 * mm),
        Paragraph("Journey", styles["Heading3"]),
        _table(
            [
                ["From", "To", "Departure", "Arrival"],
                [booking["origin"], booking["destination"], _fmt(booking["departure_at"]), _fmt(booking["arrival_at"])],
            ],
            [36 * mm, 36 * mm, 51 * mm, 51 * mm],
        ),
        Spacer(1, 4 * mm),
        _table(
            [
                ["Operator", booking["operator"]],
                [f"{mode} number", booking["trip_code"]],
                ["Booked by", booking["user_email"]],
                ["Payment reference", booking.get("payment_ref") or "-"],
            ],
            [45 * mm, 129 * mm],
            header=False,
        ),
        Spacer(1, 8 * mm),
        Paragraph("Passengers", styles["Heading3"]),
        _table(
            [["#", "Name", "Age"]]
            + [[str(i), p["name"], str(p["age"])] for i, p in enumerate(booking["passengers"], start=1)],
            [15 * mm, 129 * mm, 30 * mm],
        ),
        Spacer(1, 8 * mm),
        _table([["Total paid", f"INR {booking['amount']:,.2f}"]], [45 * mm, 129 * mm], header=False),
        Spacer(1, 12 * mm),
        Paragraph(
            "This is a dummy ticket generated by a demo project. It is not valid for travel.",
            styles["Italic"],
        ),
    ]
    doc.build(elements)
    return buffer.getvalue()
